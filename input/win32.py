# Limited query rights are enough for the executable path and, unlike full
# query access, are granted for processes at the same integrity level without
# elevation.
PROCESS_QUERY_LIMITED_INFORMATION: Final = 0x1000

kernel32.OpenProcess.argtypes = (wt.DWORD, wt.BOOL, wt.DWORD)
kernel32.OpenProcess.restype = wt.HANDLE

kernel32.QueryFullProcessImageNameW.argtypes = (
    wt.HANDLE,
    wt.DWORD,
    wt.LPWSTR,
    ctypes.POINTER(wt.DWORD),
)
kernel32.QueryFullProcessImageNameW.restype = wt.BOOL

kernel32.CloseHandle.argtypes = (wt.HANDLE,)
kernel32.CloseHandle.restype = wt.BOOL


# --- Convenience wrappers --------------------------------------------------

_TEXT_BUFFER = 512


def foreground_window() -> int:
    """Handle of the window the user is currently working in, or 0."""
    return user32.GetForegroundWindow() or 0


def window_title(hwnd: int) -> str:
    """Title bar text of a window, or an empty string."""
    if not hwnd:
        return ""
    buffer = ctypes.create_unicode_buffer(_TEXT_BUFFER)
    user32.GetWindowTextW(hwnd, buffer, _TEXT_BUFFER)
    return buffer.value


def window_class(hwnd: int) -> str:
    """Window class name, which identifies the application more reliably
    than a title the user's own document can change."""
    if not hwnd:
        return ""
    buffer = ctypes.create_unicode_buffer(_TEXT_BUFFER)
    user32.GetClassNameW(hwnd, buffer, _TEXT_BUFFER)
    return buffer.value


def window_process_id(hwnd: int) -> int:
    """Process owning a window, or 0."""
    if not hwnd:
        return 0
    pid = wt.DWORD()
    user32.GetWindowThreadProcessId(hwnd, ctypes.byref(pid))
    return pid.value


def process_name(pid: int) -> str:
    """Executable file name of a process, lowercased, or an empty string.

    The only dependable way to tell what an application actually is. Window
    class is not enough: every Electron application, Visual Studio Code
    included, reports the same class as Chrome, so a check based on class
    alone would treat a code editor as a browser.
    """
    if not pid:
        return ""

    handle = kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, pid)
    if not handle:
        return ""

    try:
        size = wt.DWORD(_TEXT_BUFFER)
        buffer = ctypes.create_unicode_buffer(_TEXT_BUFFER)
        if not kernel32.QueryFullProcessImageNameW(handle, 0, buffer, ctypes.byref(size)):
            return ""
        return buffer.value.rsplit("\\", 1)[-1].lower()
    finally:
        kernel32.CloseHandle(handle)


def send_keys(*combination: int) -> bool:
    """Press a set of keys together and release them in reverse order.

    ``send_keys(VK_MENU, VK_LEFT)`` is Alt+Left. Events are delivered to
    whichever window has focus; nothing here changes focus, deliberately.

    Returns:
        True if Windows accepted every event. A False here usually means a
        more privileged window has focus, which no amount of retrying fixes.
    """
    if not combination:
        return True

    events: list[INPUT] = []
    for key in combination:
        events.append(_key_event(key, down=True))
    for key in reversed(combination):
        events.append(_key_event(key, down=False))

    array = (INPUT * len(events))(*events)
    sent = user32.SendInput(len(events), array, ctypes.sizeof(INPUT))
    return sent == len(events)


def _key_event(key: int, *, down: bool) -> INPUT:
    flags = 0 if down else KEYEVENTF_KEYUP
    if key in EXTENDED_KEYS:
        flags |= KEYEVENTF_EXTENDEDKEY

    event = INPUT(type=INPUT_KEYBOARD)
    event.ki = KEYBDINPUT(wVk=key, wScan=0, dwFlags=flags, time=0, dwExtraInfo=0)
    return event
